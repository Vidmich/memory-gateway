#: Runway. Kept in step with ``app.db.models.request_log.PARTITION_DAYS_AHEAD``; a test
#: asserts they agree, because a shorter runway here would silently send every row to the
#: default partition after the window closed.
DAYS_AHEAD = 30
#: One day behind, so a row written during the migration itself — or by a worker whose
#: clock is a little slow — still lands in a real partition.
DAYS_BEHIND = 1


