"""Request logs and transcripts, partitioned by day.

Hand-written rather than autogenerated, because Alembic cannot express ``PARTITION BY``
and would produce two ordinary tables that work perfectly until the first retention run
has to delete a hundred million rows from underneath a live proxy.

Three decisions are baked into the DDL below.

**Daily range partitions on ``created_at``.** Retention (task 17) becomes ``DROP TABLE``
on a partition, which takes a brief exclusive lock on one day's data and returns the disk
immediately. The alternative — ``DELETE ... WHERE created_at < now() - interval``  — holds
a long transaction, bloats the table, and competes with the write path for exactly as long
as it runs.

**A ``_default`` partition.** Thirty days of runway is created here and task 17 keeps it
rolling, but a deploy that stops running its jobs must not start rejecting inserts: an
insert with no matching partition is an error, and an error on the logging path is a
dropped request record at best. The default partition catches those rows so they are
merely misfiled rather than lost. Task 17 has to detach it before attaching a partition
that overlaps rows it has accumulated, which is the price of the safety net and is
written down in the task file.

**Indexes are created on the parent.** PostgreSQL propagates them to every existing and
future partition, so a partition created by task 17 is indexed without task 17 knowing
what the indexes are.

Revision ID: 0007_request_logging
Revises: 0006_gateways_keys
Create Date: 2026-09-07
"""

